export function rotOrbit(x: number, y: number, I: number, om: number, Om: number): V3 {
  const cI = Math.cos(I);
  const sI = Math.sin(I);
  const co = Math.cos(om);
  const so = Math.sin(om);
  const cO = Math.cos(Om);
  const sO = Math.sin(Om);
  return [
    (co * cO - so * sO * cI) * x + (-so * cO - co * sO * cI) * y,
    (co * sO + so * cO * cI) * x + (-so * sO + co * cO * cI) * y,
    so * sI * x + co * sI * y,
  ];
}

export function orbElems(id: string, T: number) {
  const el = ELEMENTS[id];
  const Omd = el[10] + el[11] * T;
  const w = el[8] + el[9] * T;
  return {
    a: el[0] + el[1] * T,
    e: el[2] + el[3] * T,
    I: (el[4] + el[5] * T) * D2R,
    L: el[6] + el[7] * T,
    w,
    Om: Omd * D2R,
    om: (w - Omd) * D2R,
  };
}

export function helioVec(id: string, years: number): V3 {
  const T = (JD_START + years * 365.25 - 2451545.0) / 36525;
  const q = orbElems(id, T);
  const M = (((((q.L - q.w) % 360) + 540) % 360) - 180) * D2R;
  let E = M + q.e * Math.sin(M);
  for (let i = 0; i < 12; i++) {
    E += (M - (E - q.e * Math.sin(E))) / (1 - q.e * Math.cos(E));
  }
  return rotOrbit(q.a * (Math.cos(E) - q.e), q.a * Math.sqrt(1 - q.e * q.e) * Math.sin(E), q.I, q.om, q.Om);
}
